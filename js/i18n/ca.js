export function t(key, vars) {
  let text = M[key];
  if (text === undefined) {
    if (typeof console !== 'undefined') console.warn(`[i18n] clau no trobada: ${key}`);
    return key;
  }
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}

export function hasKey(key) {
  return Object.prototype.hasOwnProperty.call(M, key);
}

/** Estats per clau (pen.status.*, t.status...) amb fallback. */
export function tStatus(group, value) {
  const map = {
    pen: { active: 'pen.status.active', finished: 'pen.status.finished', discarded: 'pen.status.discarded', deleted: 'pen.status.deleted' },
    treatment: { active: 'treatment.active', paused: 'treatment.paused', finished: 'treatment.finished' },
  };
  const key = (map[group] || {})[value];
  return key ? t(key) : String(value);
}

